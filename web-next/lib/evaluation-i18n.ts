export type EvaluationTexts = Record<keyof typeof labels, string>;
export function evaluationTexts(language: string): EvaluationTexts {
  const index = language === "pl" ? 0 : language === "de" ? 2 : 1;
  return Object.fromEntries(Object.entries(labels).map(([key, row]) => [key, row[index]])) as EvaluationTexts;
}
export function evaluationLabel(t: EvaluationTexts, value: unknown): string {
  if (typeof value !== "string" || !value) return t.noData;
  return Object.hasOwn(t, value) ? t[value as keyof EvaluationTexts] : value;
}
export function gameLabel(t: EvaluationTexts, game: string) {
  return game === "tic_tac_toe" ? t.ticTacToe : game === "nim" ? "Nim" : game === "memory" ? "Memory" : game === "sokoban" ? "Sokoban" : game;
}
