type Dictionary = { [Key in keyof typeof translations]: string };
function dictionary(column: 0 | 1 | 2): Dictionary {
  // Object.fromEntries loses literal keys in TypeScript; every entry comes from
  // the checked table above, with exactly one string per language.
  return Object.fromEntries(Object.entries(translations).map(([key, row]) => [key, row[column]])) as Dictionary;
}
export const messages = { pl: dictionary(0), en: dictionary(1), de: dictionary(2) };

export type Language = keyof typeof messages;
export function texts(language: string) { return Object.hasOwn(messages, language) ? messages[language as Language] : messages.en; }
export function statusLabel(t: ReturnType<typeof texts>, status: string) {
  if (status === "cancelling") return t.cancelPending;
  return Object.hasOwn(t, status) ? (t as Record<string, string>)[status] : t.unknown;
}
export function modeLabel(t: ReturnType<typeof texts>, mode: string) { return statusLabel(t, mode === "dialog" ? "dialog_mode" : mode); }

