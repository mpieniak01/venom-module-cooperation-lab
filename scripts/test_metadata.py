#!/usr/bin/env python3
"""Module-owned test lanes and actual changed-Python-line coverage diagnostics.

The host checker assumes venom_core filenames, so it cannot measure this repo.
This small helper keeps the host policy (80% new executable lines, full module
coverage separately >=90%) without copying the host's test orchestration.
"""

from __future__ import annotations

import argparse
import ast
import fnmatch
import hashlib
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

PACKAGE = "venom_module_cooperation_lab"
CATALOG = "config/testing/test_catalog.json"
GROUPS = {"new-code": "sonar-new-code", "ci-lite": "ci-lite", "release": "release"}
LANES = ["new-code", "ci-lite", "release"]
PROVENANCE = "test-results/coverage-provenance.json"
SONAR_WAY_MINIMUM = 80.0


def test_paths(root: Path) -> list[str]:
    paths = sorted(
        p.relative_to(root).as_posix() for p in (root / "tests").rglob("test*.py")
    )
    for path in paths:
        if (root / path).is_symlink():
            raise ValueError("symlink_test_file")
        if any(word in path.lower() for word in ("benchmark", "integration")):
            raise ValueError("slow_name_in_required_lane")
    return paths


# This is a CLI utility, not a pytest test function.
test_paths.__test__ = False  # type: ignore[attr-defined]


def catalog_data(root: Path) -> dict[str, Any]:
    return {
        "version": 1,
        "owner": "venom-module-cooperation-lab",
        "tests": [
            {
                "path": path,
                "domain": "cooperation_lab",
                "test_type": "unit",
                "intent": "regression",
                "primary_lane": "new-code",
                "allowed_lanes": LANES,
                "rationale": "Module CPU regression and changed-code coverage.",
            }
            for path in test_paths(root)
        ],
    }


def encoded(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def sync_catalog(root: Path, *, check: bool) -> None:
    target = root / CATALOG
    expected = encoded(catalog_data(root))
    if check:
        if not target.is_file() or target.read_text() != expected:
            raise ValueError("test_catalog_out_of_sync")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)


def sync_groups(root: Path, *, check: bool) -> None:
    sync_catalog(root, check=True)
    body = "# Generated by scripts/test_metadata.py; all module tests are CPU-only.\n"
    body += "".join(path + "\n" for path in test_paths(root))
    for group in GROUPS.values():
        target = root / "config/pytest-groups" / (group + ".txt")
        if check:
            if not target.is_file() or target.read_text() != body:
                raise ValueError("test_groups_out_of_sync")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body)


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def source_identity(root: Path) -> dict[str, str]:
    paths = {
        p
        for name in (PACKAGE, "tests", "scripts")
        for p in (root / name).rglob("*.py")
        if "__pycache__" not in p.parts
    }
    paths.update(
        root / name
        for name in ("Makefile", "pyproject.toml", "sonar-project.properties", CATALOG)
    )
    paths.update((root / "config/pytest-groups").glob("*.txt"))
    return {
        path.relative_to(root).as_posix(): sha256(path)
        for path in sorted(paths)
        if path.is_file()
    }


def write_provenance(root: Path, coverage_xml: Path) -> None:
    if not coverage_xml.is_file():
        raise ValueError("coverage_xml_missing")
    target = root / PROVENANCE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        encoded(
            {
                "version": 1,
                "coverage_sha256": sha256(coverage_xml),
                "sources": source_identity(root),
            }
        )
    )


def check_provenance(root: Path, coverage_xml: Path) -> None:
    target = root / PROVENANCE
    if not target.is_file():
        raise ValueError("coverage_provenance_missing_run_check_python")
    stamp = json.loads(target.read_text())
    if (
        stamp.get("version") != 1
        or stamp.get("coverage_sha256") != sha256(coverage_xml)
        or stamp.get("sources") != source_identity(root)
    ):
        raise ValueError("coverage_stale_run_check_python")


def git(root: Path, *arguments: str) -> str:
    result = subprocess.run(
        ["git", *arguments], cwd=root, capture_output=True, text=True, check=False
    )
    if result.returncode:
        raise ValueError("git_diff_base_unavailable")
    return result.stdout


def parse_changed_lines(diff: str) -> dict[str, set[int]]:
    changed: dict[str, set[int]] = {}
    current: str | None = None
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            current = line[6:]
        elif line.startswith("+++ "):
            current = None
        elif current and line.startswith("@@ "):
            match = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", line)
            if not match:
                raise ValueError("invalid_git_diff")
            first, count = int(match[1]), int(match[2] or "1")
            changed.setdefault(current, set()).update(range(first, first + count))
    return changed


def changed_lines(root: Path, diff_base: str) -> tuple[str, dict[str, set[int]]]:
    base = git(root, "merge-base", diff_base, "HEAD").strip()
    diff = git(
        root,
        "diff",
        "--no-ext-diff",
        "--no-color",
        "--no-renames",
        "-U0",
        base,
        "--",
        PACKAGE,
    )
    changed = parse_changed_lines(diff)
    # git diff does not include new untracked files; all their lines are new.
    for name in git(
        root, "ls-files", "--others", "--exclude-standard", "-z", "--", PACKAGE
    ).split("\0"):
        if name.endswith(".py"):
            changed[name] = set(
                range(1, len((root / name).read_text().splitlines()) + 1)
            )
    return base, {
        name: lines for name, lines in changed.items() if name.endswith(".py") and lines
    }


def coverage_hits(root: Path, path: Path) -> dict[str, dict[int, int]]:
    hits: dict[str, dict[int, int]] = {}
    for cls in ET.parse(path).getroot().findall(".//class"):
        name = cls.get("filename", "").replace("\\", "/")
        if not name:
            continue
        if name.startswith(str(root) + "/"):
            name = name[len(str(root)) + 1 :]
        if not name.startswith(PACKAGE + "/"):
            name = PACKAGE + "/" + name
        lines = hits.setdefault(name, {})
        for line in cls.findall("./lines/line"):
            number, count = int(line.attrib["number"]), int(line.get("hits", "0"))
            if number < 0 or count < 0:
                raise ValueError("invalid_coverage_xml")
            lines[number] = max(lines.get(number, 0), count)
    return hits


def exclusions(root: Path) -> list[str]:
    config = root / "sonar-project.properties"
    if not config.is_file():
        return []
    for line in config.read_text().splitlines():
        if line.startswith("sonar.coverage.exclusions="):
            return [
                part.strip()
                for part in line.split("=", 1)[1].split(",")
                if part.strip()
            ]
    return []


def minimum_threshold(host: Path) -> float:
    policy = host / "make/tests.mk"
    if not policy.is_file():
        return SONAR_WAY_MINIMUM
    match = re.search(
        r"^NEW_CODE_CHANGED_LINES_MIN\s*\?=\s*(\d+(?:\.\d+)?)\s*$",
        policy.read_text(),
        re.MULTILINE,
    )
    return max(SONAR_WAY_MINIMUM, float(match[1])) if match else SONAR_WAY_MINIMUM


def has_executable_code(path: Path) -> bool:
    return any(
        not (
            isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        )
        for node in ast.parse(path.read_text()).body
    )


def coverage_report(
    root: Path,
    host: Path,
    coverage_xml: Path,
    diff_base: str,
    minimum: float | None = None,
) -> dict[str, Any]:
    required = minimum_threshold(host)
    if minimum is not None:
        if not required <= minimum <= 100:
            raise ValueError("coverage_threshold_cannot_be_lowered")
        required = minimum
    base, changed = changed_lines(root, diff_base)
    ignored = exclusions(root)
    changed = {
        name: lines
        for name, lines in changed.items()
        if not any(fnmatch.fnmatch(name, pattern) for pattern in ignored)
    }
    if not changed:
        return {
            "pass": True,
            "status": "not_applicable",
            "diff_base": diff_base,
            "base_sha": base,
            "covered": 0,
            "total": 0,
            "rate_percent": None,
            "required_percent": required,
            "files": [],
        }
    if not coverage_xml.is_file():
        raise ValueError("coverage_xml_missing")
    check_provenance(root, coverage_xml)
    hits = coverage_hits(root, coverage_xml)
    rows = []
    missing = []
    covered = total = 0
    for name, lines in sorted(changed.items()):
        if name not in hits and has_executable_code(root / name):
            missing.append(name)
        file_hits = hits.get(name, {})
        executable = sorted(lines & file_hits.keys())
        absent = [line for line in executable if file_hits[line] == 0]
        count = len(executable)
        covered += count - len(absent)
        total += count
        rows.append(
            {
                "path": name,
                "covered": count - len(absent),
                "total": count,
                "uncovered_lines": absent,
            }
        )
    rate = covered * 100.0 / total if total else None
    return {
        "pass": not missing and (rate is None or rate + 1e-9 >= required),
        "status": "measured" if total else "no_executable_changes",
        "diff_base": diff_base,
        "base_sha": base,
        "covered": covered,
        "total": total,
        "rate_percent": round(rate, 2) if rate is not None else None,
        "required_percent": required,
        "missing_coverage_files": missing,
        "files": rows,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command",
        choices=[
            "catalog-sync",
            "catalog-check",
            "groups-sync",
            "groups-check",
            "coverage-stamp",
            "coverage",
        ],
    )
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--host", type=Path, default=Path("../.."))
    parser.add_argument(
        "--coverage-xml", type=Path, default=Path("test-results/coverage.xml")
    )
    parser.add_argument("--diff-base", default="origin/main")
    parser.add_argument("--min-coverage", type=float)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    xml = (
        args.coverage_xml
        if args.coverage_xml.is_absolute()
        else root / args.coverage_xml
    )
    try:
        if args.command.startswith("catalog-"):
            sync_catalog(root, check=args.command.endswith("check"))
        elif args.command.startswith("groups-"):
            sync_groups(root, check=args.command.endswith("check"))
        elif args.command == "coverage-stamp":
            write_provenance(root, xml)
        else:
            report = coverage_report(
                root, args.host.resolve(), xml, args.diff_base, args.min_coverage
            )
            output = root / "test-results/changed-lines-coverage.json"
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(encoded(report))
            print(encoded(report), end="")
            return 0 if report["pass"] else 1
        print(args.command + ": PASS")
        return 0
    except (ValueError, OSError, ET.ParseError) as exc:
        print("Quality gate failed: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
